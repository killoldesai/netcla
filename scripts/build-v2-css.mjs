#!/usr/bin/env node
/*
 * Builds the v2 (monday-style) design assets for the live site from the approved prototype in html-prototype/v2/.
 *
 *   node scripts/build-v2-css.mjs
 *
 * Every rule is scoped under `.v2` (the wrapper element of each v2 page), so class names cannot clash with the
 * legacy site CSS or the older `.nx` design:  :root, html, body -> .v2   and   .btn -> .v2 .btn
 * Keyframes get a `v2-` prefix, weight 500 is mapped to 600 and 300 to 400 (Poppins is self-hosted in 400 and 600).
 *
 * Output (all generated, never edit by hand):
 *   public/assets/v2/site.css           core.css + components.css (tokens, header, shared components)
 *   public/assets/v2/pages/<name>.css   html-prototype/v2/css/pages/<name>.css (+ css/live/<name>.css for live-only rules)
 *   public/assets/v2/home.css           html-prototype/v2/css/home.css (+ css/live/home.css)
 *   public/assets/v2/img/*.webp         html-prototype/v2/img/*.webp (generated characters, icons, scenes)
 *   src/site/v2/icon-sprite.ts          inline line-icon sprite from html-prototype/v2/partials/icons.html
 *   public/assets/v2/core.js            html-prototype/v2/js/core.js (reference only; the site uses src/site/v2/behaviors.tsx)
 */
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const REPO = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')), '..');
const SRC = path.join(REPO, 'html-prototype', 'v2');
const OUT = path.join(REPO, 'public', 'assets', 'v2');
const read = (f) => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8') : '');

const keyframeNames = new Set();
const allCss = [path.join(SRC, 'css', 'core.css'), path.join(SRC, 'css', 'components.css'), path.join(SRC, 'css', 'home.css'),
  ...['pages', 'live'].flatMap((d) => (fs.existsSync(path.join(SRC, 'css', d)) ? fs.readdirSync(path.join(SRC, 'css', d)).map((f) => path.join(SRC, 'css', d, f)) : []))];
for (const f of allCss) for (const m of read(f).matchAll(/@keyframes\s+([a-zA-Z0-9_-]+)/g)) keyframeNames.add(m[1]);

function scopeSelector(sel) {
  const s = sel.trim();
  if (/^(:root|html|body)$/.test(s)) return '.v2';
  if (/^(:root|html|body)\s+/.test(s)) return s.replace(/^(:root|html|body)\s+/, '.v2 ');
  if (/^(html|body)[.:[]/.test(s)) return s.replace(/^(html|body)/, '.v2');
  // Elements that start hidden and are revealed by script only get hidden once JS has added .js-on, so the content shows without JS.
  if (/\.rv|\.wf__step|\.wf__ln/.test(s)) return `.v2.js-on ${s}`;
  return `.v2 ${s}`;
}

const scope = () => ({
  postcssPlugin: 'v2-scope',
  Once(root) {
    root.walkAtRules('import', (r) => r.remove());
    root.walkAtRules('keyframes', (r) => { if (!r.params.startsWith('v2-')) r.params = `v2-${r.params}`; });
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
      rule.selectors = [...new Set(rule.selectors.map(scopeSelector))];
    });
    root.walkDecls((d) => {
      if (/^animation(-name)?$/.test(d.prop)) d.value = d.value.replace(/[a-zA-Z0-9_-]+/g, (w) => (keyframeNames.has(w) && !w.startsWith('v2-') ? `v2-${w}` : w));
      if (d.prop === 'font-weight') d.value = d.value.trim() === '500' ? '600' : d.value.trim() === '300' ? '400' : d.value;
      if (d.prop === 'font') d.value = d.value.trim().replace(/^500\s/, '600 ').replace(/^300\s/, '400 ');
    });
    root.walkAtRules('media', (r) => { if (!r.nodes?.length) r.remove(); });
  },
});

async function build(css, out) {
  const result = await postcss([scope()]).process(css, { from: undefined });
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `/* Generated by scripts/build-v2-css.mjs from html-prototype/v2/css. Scoped to .v2. */\n${result.css.trim()}\n`);
  return path.relative(REPO, out) + ' ' + result.css.length;
}

const logs = [];
logs.push(await build(read(path.join(SRC, 'css', 'core.css')) + '\n' + read(path.join(SRC, 'css', 'components.css')) + '\n' + read(path.join(SRC, 'css', 'live', 'site.css')), path.join(OUT, 'site.css')));
logs.push(await build(read(path.join(SRC, 'css', 'home.css')) + '\n' + read(path.join(SRC, 'css', 'live', 'home.css')), path.join(OUT, 'home.css')));
const names = new Set([
  ...(fs.existsSync(path.join(SRC, 'css', 'pages')) ? fs.readdirSync(path.join(SRC, 'css', 'pages')) : []),
  ...(fs.existsSync(path.join(SRC, 'css', 'live')) ? fs.readdirSync(path.join(SRC, 'css', 'live')) : []),
].filter((f) => f.endsWith('.css') && !['site.css', 'home.css'].includes(f)));
for (const f of names) {
  logs.push(await build(read(path.join(SRC, 'css', 'pages', f)) + '\n' + read(path.join(SRC, 'css', 'live', f)), path.join(OUT, 'pages', f)));
}

// Images (webp only; PNG masters stay in html-prototype/v2/img)
fs.mkdirSync(path.join(OUT, 'img'), { recursive: true });
let imgs = 0;
for (const f of fs.readdirSync(path.join(SRC, 'img')).filter((f) => f.endsWith('.webp'))) { fs.copyFileSync(path.join(SRC, 'img', f), path.join(OUT, 'img', f)); imgs++; }
logs.push(`images ${imgs}`);

// Reference copy of the prototype behaviours
fs.copyFileSync(path.join(SRC, 'js', 'core.js'), path.join(OUT, 'core.js'));

// Inline line-icon sprite as a TypeScript module
const sprite = read(path.join(SRC, 'partials', 'icons.html')).trim();
const names2 = [...sprite.matchAll(/<symbol id="i-([a-z0-9-]+)"/g)].map((m) => m[1]);
fs.mkdirSync(path.join(REPO, 'src', 'site', 'v2'), { recursive: true });
fs.writeFileSync(
  path.join(REPO, 'src', 'site', 'v2', 'icon-sprite.ts'),
  `// Generated by scripts/build-v2-css.mjs from html-prototype/v2/partials/icons.html. Do not edit.\n` +
    `export const V2_ICON_NAMES = ${JSON.stringify(names2)} as const;\nexport type V2IconName = (typeof V2_ICON_NAMES)[number];\n` +
    `export const V2_ICON_SPRITE = ${JSON.stringify(sprite)};\n`,
);
logs.push(`icons ${names2.length}`);
console.log(logs.join('\n'));
