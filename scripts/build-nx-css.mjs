#!/usr/bin/env node
/*
 * Builds the redesign stylesheets in public/assets/nx/ from the approved HTML prototype.
 *
 *   node scripts/build-nx-css.mjs
 *
 * Every rule is scoped under `.nx` (the wrapper element of each public page), so the
 * prototype's generic class names cannot clash with the global admin and site CSS:
 *   :root, html, body  ->  .nx
 *   .section           ->  .nx .section
 * Dark-theme rules are dropped (the live site is light only), keyframes get an `nx-`
 * prefix, the Google Fonts import is removed (Poppins is self-hosted) and weight 500,
 * which the self-hosted font set does not have, is mapped to 600.
 *
 * Output: public/assets/nx/site.css (tokens + components + shared sections)
 *         public/assets/nx/proto/<page>.css (reference copy of each prototype page, scoped)
 * public/assets/nx/pages/*.css are hand-maintained per renderer (start from proto/) and never overwritten.
 */
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const REPO = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1')), '..');
const SRC = path.join(REPO, 'html-prototype', 'css');
const OUT = path.join(REPO, 'public', 'assets', 'nx');

const keyframeNames = new Set();
const collectKeyframes = (css) => {
  for (const m of css.matchAll(/@keyframes\s+([a-zA-Z0-9_-]+)/g)) keyframeNames.add(m[1]);
};

function scopeSelector(sel) {
  const s = sel.trim();
  if (/\[data-theme="dark"\]/.test(s)) return null;
  const root = s.replace(/\[data-theme="light"\]/g, ':root');
  if (/^(:root|html|body)$/.test(root)) return '.nx';
  if (/^(:root|html|body)\s+/.test(root)) return root.replace(/^(:root|html|body)\s+/, '.nx ');
  if (/^(html|body)[.:[]/.test(root)) return root.replace(/^(html|body)/, '.nx');
  return `.nx ${root}`;
}

const scope = () => ({
  postcssPlugin: 'nx-scope',
  Once(root) {
    root.walkAtRules('import', (r) => r.remove());
    root.walkAtRules('keyframes', (r) => {
      if (!r.params.startsWith('nx-')) r.params = `nx-${r.params}`;
    });
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
      const scoped = rule.selectors.map(scopeSelector).filter(Boolean);
      if (!scoped.length) rule.remove();
      else rule.selectors = [...new Set(scoped)];
    });
    root.walkDecls((d) => {
      if (/^animation(-name)?$/.test(d.prop)) {
        d.value = d.value.replace(/[a-zA-Z0-9_-]+/g, (w) => (keyframeNames.has(w) && !w.startsWith('nx-') ? `nx-${w}` : w));
      }
      if (d.prop === 'font-weight' && d.value.trim() === '500') d.value = '600';
      if (d.prop === 'font' && /^500\s/.test(d.value.trim())) d.value = d.value.trim().replace(/^500/, '600');
    });
    root.walkAtRules('media', (r) => { if (!r.nodes?.length) r.remove(); });
  },
});

async function build(files, out) {
  const css = files.map((f) => fs.readFileSync(f, 'utf8')).join('\n');
  const result = await postcss([scope()]).process(css, { from: undefined });
  const header = `/* Generated by scripts/build-nx-css.mjs from html-prototype/css. Scoped to .nx, light theme only. */\n`;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, header + result.css.trim() + '\n');
  return result.css.length;
}

const shared = ['tokens.css', 'components.css', 'sections.css'].map((f) => path.join(SRC, f));
for (const f of [...shared, ...fs.readdirSync(path.join(SRC, 'pages')).map((p) => path.join(SRC, 'pages', p))]) collectKeyframes(fs.readFileSync(f, 'utf8'));

const sizes = [`site.css ${await build(shared, path.join(OUT, 'site.css'))}`];
sizes.push(`proto/home.css ${await build([path.join(SRC, 'home.css')], path.join(OUT, 'proto', 'home.css'))}`);
for (const p of fs.readdirSync(path.join(SRC, 'pages')).filter((p) => p.endsWith('.css'))) {
  sizes.push(`proto/${p} ${await build([path.join(SRC, 'pages', p)], path.join(OUT, 'proto', p))}`);
}
console.log(sizes.join('\n'));
